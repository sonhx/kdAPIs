package com.surveycomments;

import com.surveycomments.classify.ClassificationResult;
import com.surveycomments.report.ReportServiceImpl;
import com.surveycomments.run.Run;
import com.surveycomments.run.RunRepository;
import org.apache.poi.ss.usermodel.Sheet;
import org.apache.poi.ss.usermodel.Workbook;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.when;

/**
 * Unit tests for {@link ReportServiceImpl} (Task T7).
 * Fast, offline tests verifying Excel (.xlsx) workbook and CSV generation.
 */
@ExtendWith(MockitoExtension.class)
class ReportServiceTest {

    @Mock
    private RunRepository runRepository;

    @InjectMocks
    private ReportServiceImpl reportService;

    private Run sampleRun;
    private List<ClassificationResult> sampleResults;

    @BeforeEach
    void setUp() {
        sampleRun = new Run("run-abc", "survey-2026-spring", "SYNC");

        ClassificationResult r1 = new ClassificationResult(
                "c001", "K12",
                List.of(
                        new ClassificationResult.ThemeResult("teaching", "positive", "Thầy dạy dễ hiểu", true),
                        new ClassificationResult.ThemeResult("facilities", "negative", "máy lạnh hỏng", false)
                ),
                "mixed", 0.95, false, false, "gemini-3.8-flash", "p0", "v0.2-draft", 100, 20);

        ClassificationResult r2 = new ClassificationResult(
                "c002", "K13",
                List.of(new ClassificationResult.ThemeResult("schedule", "negative", "Lịch học dày", true)),
                "negative", 0.90, false, false, "gemini-3.8-flash", "p0", "v0.2-draft", 100, 20);

        ClassificationResult r3 = new ClassificationResult(
                "c003", "K14",
                List.of(new ClassificationResult.ThemeResult("online_systems", "negative", "Web sập", true)),
                "negative", 0.88, false, true, "gemini-3.8-flash", "p0", "v0.2-draft", 100, 20);

        ClassificationResult r4 = new ClassificationResult(
                "c004", "K12",
                List.of(new ClassificationResult.ThemeResult("other", "neutral", "chưa rõ", false)),
                "neutral", 0.50, true, false, "gemini-3.8-flash", "p0", "v0.2-draft", 100, 20);

        sampleResults = List.of(r1, r2, r3, r4);
    }

    @Test
    void generateExcelReport_generatesValid5SheetWorkbook() throws Exception {
        when(runRepository.findById("run-abc")).thenReturn(Optional.of(sampleRun));
        when(runRepository.findResultsByRunId("run-abc")).thenReturn(sampleResults);

        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        reportService.generateExcelReport("run-abc", baos);

        byte[] bytes = baos.toByteArray();
        assertTrue(bytes.length > 0, "Excel output should not be empty");

        // Verify valid XSSFWorkbook can parse the generated bytes
        try (Workbook wb = new XSSFWorkbook(new ByteArrayInputStream(bytes))) {
            assertEquals(5, wb.getNumberOfSheets(), "Workbook must contain exactly 5 sheets");

            assertEquals("Tổng quan & Chủ đề", wb.getSheetAt(0).getSheetName());
            assertEquals("Phân tích theo khóa", wb.getSheetAt(1).getSheetName());
            assertEquals("Kiến nghị & Đề xuất", wb.getSheetAt(2).getSheetName());
            assertEquals("Hàng đợi kiểm duyệt", wb.getSheetAt(3).getSheetName());
            assertEquals("Mẫu kiểm tra ngẫu nhiên", wb.getSheetAt(4).getSheetName());

            // Check Sheet 1 (Overview)
            Sheet s1 = wb.getSheetAt(0);
            assertEquals("BÁO CÁO PHÂN TÍCH Ý KIẾN KHẢO SÁT SINH VIÊN", s1.getRow(0).getCell(0).getStringCellValue());
            assertEquals("Mã đợt phân tích (Run ID):", s1.getRow(2).getCell(0).getStringCellValue());
            assertEquals("run-abc", s1.getRow(2).getCell(1).getStringCellValue());

            // Check Sheet 3 (Suggestions - only c003 has suggestion)
            Sheet s3 = wb.getSheetAt(2);
            assertEquals(2, s3.getPhysicalNumberOfRows(), "Header row + 1 suggestion row");
            assertEquals("c003", s3.getRow(1).getCell(1).getStringCellValue());

            // Check Sheet 4 (Review Queue - c004 has low confidence, needs review, theme other)
            Sheet s4 = wb.getSheetAt(3);
            assertEquals(2, s4.getPhysicalNumberOfRows(), "Header row + 1 review item");
            assertEquals("c004", s4.getRow(1).getCell(1).getStringCellValue());

            // Check Sheet 5 (Spot Check - at least 1 sample item)
            Sheet s5 = wb.getSheetAt(4);
            assertTrue(s5.getPhysicalNumberOfRows() >= 2, "Header row + at least 1 spot check sample item");
        }
    }

    @Test
    void generateCsvReport_generatesValidCsvWithBom() {
        when(runRepository.findResultsByRunId("run-abc")).thenReturn(sampleResults);

        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        reportService.generateCsvReport("run-abc", baos);

        byte[] bytes = baos.toByteArray();
        assertTrue(bytes.length > 3);
        // Verify UTF-8 BOM
        assertEquals((byte) 0xEF, bytes[0]);
        assertEquals((byte) 0xBB, bytes[1]);
        assertEquals((byte) 0xBF, bytes[2]);

        String csvText = new String(bytes, 3, bytes.length - 3, StandardCharsets.UTF_8);
        assertTrue(csvText.contains("theme_id,theme_name_vi,mentions,commenter_share_pct"));
        assertTrue(csvText.contains("\"teaching\",\"Giảng viên & giảng dạy\",1,25.0%"));
        assertTrue(csvText.contains("\"facilities\",\"Cơ sở vật chất học tập\",1,25.0%"));
    }

    @Test
    void generateExcelReport_missingRun_throwsException() {
        when(runRepository.findById("missing")).thenReturn(Optional.empty());

        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        assertThrows(IllegalArgumentException.class, () ->
                reportService.generateExcelReport("missing", baos));
    }
}

